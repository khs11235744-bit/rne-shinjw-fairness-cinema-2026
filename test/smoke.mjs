import { preview } from 'vite';
import { createRequire } from 'node:module';
import path from 'node:path';
import fs from 'node:fs';
import assert from 'node:assert/strict';

const require=createRequire(import.meta.url);
const {chromium}=require(path.join(process.env.USERPROFILE,'Documents','Pohang-RnE-Studio','node_modules','playwright'));
const output=path.join(process.cwd(),'test-results');
fs.mkdirSync(output,{recursive:true});
const srv=await preview({preview:{host:'127.0.0.1',port:4177,strictPort:true}});
let browser,errors=[],messages=[];
try{
 browser=await chromium.launch({channel:'chrome',headless:true});
 const ctx=await browser.newContext({viewport:{width:1600,height:900},deviceScaleFactor:1,acceptDownloads:false});
 const page=await ctx.newPage();
 page.on('pageerror',e=>errors.push(String(e)));
 page.on('console',m=>{if(m.type()==='error')messages.push('console: '+m.text())});
 const base='http://127.0.0.1:4177/';
 await page.goto(base,{waitUntil:'networkidle',timeout:60000});
 await page.locator('.scene').first().waitFor({timeout:25000});
 await page.waitForTimeout(1000); console.log('LAYOUT='+JSON.stringify(await page.evaluate(()=>['.reveal','.reveal .slides','.reveal .slides>section.scene'].map(sel=>{const e=document.querySelector(sel),r=e.getBoundingClientRect(),s=getComputedStyle(e);return {sel,x:r.x,y:r.y,width:r.width,height:r.height,left:s.left,top:s.top,transform:s.transform,position:s.position}}))));
 const count=await page.locator('.reveal .slides > section.scene').count(); console.log('DOM_DEBUG='+JSON.stringify(await page.evaluate(()=>({revealCount:document.querySelectorAll('.reveal').length,slidesContainers:document.querySelectorAll('.reveal .slides').length,allSceneIds:[...document.querySelectorAll('.scene')].map(x=>x.dataset.id),modules:document.querySelectorAll('script').length,otherScenes:[...document.querySelectorAll('.scene')].filter(x=>!x.dataset.id).map(x=>({tag:x.tagName,className:x.className})).slice(0,13)}))));assert.equal(count,11,'11장 구성');
 await page.screenshot({path:path.join(output,'scene-01.jpg'),type:'jpeg',quality:78});
 await page.evaluate(()=>window.rneDeck.slide(1));
 await page.waitForTimeout(600);
 await page.locator('[data-choice=spent]').click();
 await page.waitForTimeout(950);
 const money=await page.locator('#bill-a').innerText();assert.match(money,/6,000/,'영수증 계산 전환');
 await page.evaluate(()=>window.rneDeck.slide(3));
 await page.waitForTimeout(1800);
 const metric=await page.locator('[data-count="77.4"]').first().innerText();
 assert.match(metric,/77.4/,'77.4 데이터');
 const chartCount=await page.locator('#precision-chart canvas').count();assert.ok(chartCount>0,'ECharts canvas');
 await page.screenshot({path:path.join(output,'scene-04.jpg'),type:'jpeg',quality:80});
 await page.evaluate(()=>window.rneDeck.slide(8));
 await page.waitForTimeout(900);
 await page.screenshot({path:path.join(output,'scene-09.jpg'),type:'jpeg',quality:80});
 await page.evaluate(()=>window.rneDeck.slide(10));
 await page.waitForTimeout(600);
 await page.screenshot({path:path.join(output,'scene-11.jpg'),type:'jpeg',quality:80});
 await page.locator('#btn-qa').click();
 await page.locator('#qa-root.visible').waitFor();
 assert.match(await page.locator('#qa-question').innerText(),/포항고/);
 await page.locator('#qa-answer-toggle').click();
 assert.equal(await page.locator('#qa-answer').isVisible(),true,'모범답변 표시');
 await page.locator('#qa-grade').selectOption('5');
 assert.match(await page.locator('#qa-summary').innerText(),/1\/32/);
 await page.locator('#qa-close').click();
 await page.locator('#btn-sources').click();
 await page.locator('#refs-root.visible').waitFor();
 await page.locator('#refs-close').click();
 const popPromise=page.waitForEvent('popup',{timeout:10000});
 await page.locator('#btn-presenter').click();
 const pop=await popPromise;
 await pop.locator('#presenter-notes').waitFor({timeout:15000});
 assert.ok((await pop.locator('#presenter-notes').innerText()).length>90,'발표 대본 로딩');
 await pop.locator('#pres-prev').click();
 await page.waitForTimeout(700);
 const actual=await page.evaluate(()=>window.rneDeck.getIndices().h);
 assert.equal(actual,9,'발표자 창 동기화');
 await pop.locator('#pres-start').click();
 await page.waitForTimeout(550);
 assert.ok((await page.locator('#clock').innerText())!=='07:00','동기화된 타이머');
 await pop.close();
 const mobile=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1});
 mobile.on('pageerror',e=>errors.push('mobile: '+String(e)));
 await mobile.goto(base,{waitUntil:'domcontentloaded',timeout:60000});
 await mobile.locator('.mobile-app').waitFor({timeout:20000});
 await mobile.screenshot({path:path.join(output,'mobile.jpg'),type:'jpeg',quality:70});
 await mobile.close();
 const report={passed:true,slideCount:count,chartCanvas:chartCount,presenterSync:true,qaCount:32,clockSync:true,errors,messages,shots:['scene-01.jpg','scene-04.jpg','scene-09.jpg','scene-11.jpg','mobile.jpg']};
 fs.writeFileSync(path.join(output,'qa-report.json'),JSON.stringify(report,null,2),'utf8');
 console.log('QA_REPORT='+JSON.stringify(report));
 if(errors.length)process.exitCode=2;
}catch(e){
 const report={passed:false,error:String(e?.stack||e),errors,messages};
 fs.writeFileSync(path.join(output,'qa-report.json'),JSON.stringify(report,null,2),'utf8');
 console.error('QA_FAILED='+JSON.stringify(report));process.exitCode=1;
}finally{
 if(browser)await browser.close().catch(()=>{});
 await new Promise(resolve=>srv.httpServer.close(resolve));
}
